#!/usr/bin/env python3
"""gen-info.py DOOM_SRC_DIR OUT_NUC: Chocolate Doom's info tables as Nucleus.

Reads info.h, info.c, sounds.h and p_mobj.h from DOOM_SRC_DIR
(../chocolate-doom/src/doom) and writes the sprite, state, mobj-type, sound
and action enums, the mobj flags, and the states and mobjinfo tables.
"""
import re, sys

d = sys.argv[1]
info_h = open(f'{d}/info.h').read()
info_c = open(f'{d}/info.c').read()
sounds_h = open(f'{d}/sounds.h').read()
p_mobj_h = open(f'{d}/p_mobj.h').read()

def strip(s):
    return re.sub(r'//.*', '', re.sub(r'/\*.*?\*/', '', s, flags=re.S))

def enum_members(src, last):
    """The members of the C enum whose last member is `last`."""
    src = strip(src)
    i = src.index(last)
    body = src[src.rindex('{', 0, i) + 1:i]
    return [m.split('=')[0].strip() for m in body.split(',') if m.strip()]

def nuc(c_name):
    return c_name.replace('_', '-').upper()

def action_name(c_name):
    """A_WeaponReady -> A-WEAPONREADY: C's camel case doesn't split cleanly
    (A_BFGsound, A_SPosAttack), and this keeps the name greppable."""
    return 'A-' + c_name[2:].upper()

sprites = enum_members(info_h, 'NUMSPRITES')
states = enum_members(info_h, 'NUMSTATES')
mobjtypes = enum_members(info_h, 'NUMMOBJTYPES')
sfx = enum_members(sounds_h, 'NUMSFX')

flags = {}
for name, val in re.findall(r'\b(MF_\w+)\s*=\s*(0x[0-9a-fA-F]+|\d+)', p_mobj_h):
    flags[name] = int(val, 0)

symbols = {}
symbols.update({n: i for i, n in enumerate(states)})
symbols.update({n: i for i, n in enumerate(sfx)})
symbols.update({n: i for i, n in enumerate(sprites)})
symbols.update(flags)
symbols['FRACUNIT'] = 1 << 16

def value(expr):
    expr = expr.strip()
    if re.fullmatch(r'-?\d+', expr):
        return int(expr)
    py = re.sub(r'\b[A-Za-z_]\w*\b', lambda m: str(symbols[m.group(0)]), expr)
    return eval(py, {'__builtins__': {}})

body = strip(info_c)
sprnames = re.findall(r'"(\w{4})"', re.search(r'sprnames\[\]\s*=\s*\{(.*?)\};', body, re.S).group(1))
assert sprnames == [s[4:] for s in sprites[:len(sprnames)]], 'sprnames order'

state_rows = re.findall(
    r'\{\s*(SPR_\w+)\s*,\s*([^,]+),\s*([^,]+),\s*\{\s*(\w+)\s*\}\s*,\s*(\w+)\s*,\s*([^,]+),\s*([^}]+)\}',
    re.search(r'states\[NUMSTATES\]\s*=\s*\{(.*)\};\s*mobjinfo_t', body, re.S).group(1))
assert len(state_rows) == len(states), (len(state_rows), len(states))

actions = []
for r in state_rows:
    if r[3] != 'NULL' and r[3] not in actions:
        actions.append(r[3])

mobj_body = re.search(r'mobjinfo\[NUMMOBJTYPES\]\s*=\s*\{(.*)\};', body, re.S).group(1)
mobj_rows = [[f.strip() for f in m.split(',') if f.strip()]
             for m in re.findall(r'\{([^{}]*)\}', mobj_body)]
assert len(mobj_rows) == len(mobjtypes), (len(mobj_rows), len(mobjtypes))
assert all(len(r) == 23 for r in mobj_rows)

out = ['''; Copyright (C) 1993-1996 Id Software, Inc.
; Copyright (C) 2005-2014 Simon Howard
; GPLv2 or later (Chocolate Doom info.c, info.h, sounds.h, p_mobj.h); this
; port is GPLv3, see COPYING.
;
; Generated by reference/tools/gen-info.py. Don't edit.
; A state's action is an `Action` member, which the playsim dispatches on, so
; this table doesn't depend on the code that runs the actions.

(ns doom.info)

(import-use doom.bytes)
''']

def enum(name, members, comment):
    out.append(f'; {comment}')
    out.append(f'(defenum {name}')
    for i in range(0, len(members), 6):
        out.append('  ' + ' '.join(members[i:i + 6]))
    out[-1] += ')'
    out.append('')

enum('SpriteNum', [nuc(s) for s in sprites] + ['NUMSPRITES'], 'spritenum_t')
enum('StateNum', [nuc(s) for s in states] + ['NUMSTATES'], 'statenum_t')
enum('MobjType', [nuc(s) for s in mobjtypes] + ['NUMMOBJTYPES'], 'mobjtype_t')
enum('SfxNum', [nuc(s) for s in sfx] + ['NUMSFX'], 'sfxenum_t')
enum('Action', ['A-NONE'] + [action_name(a) for a in actions], 'The functions states name, A-NONE for NULL.')

out.append('; mobj_t flags (p_mobj.h)')
for n, v in flags.items():
    out.append(f'(defconst {nuc(n)} {v})')
out.append('')

out.append('(defconst SPRITE-NAMES "' + ''.join(sprnames) + '")')
out.append('''
(defn sprite-name (s:i32):Name
  (return (name-from (unsafe/ptr+ (unsafe/cast &ui8 SPRITE-NAMES) (as i64 (* s 4))) 4)))
''')

out.append('''; frame's low bits are the frame letter; FF_FULLBRIGHT marks a lit one.
(defstruct State sprite:i32 frame:i32 tics:i32 action:i32 next:i32 misc1:i32 misc2:i32)

(defconst FF-FULLBRIGHT 0x8000)
(defconst FF-FRAMEMASK 0x7fff)

(defconst STATES (array State''')
for r, n in zip(state_rows, states):
    act = 0 if r[3] == 'NULL' else actions.index(r[3]) + 1
    vals = [symbols[r[0]], value(r[1]), value(r[2]), act, symbols[r[4]], value(r[5]), value(r[6])]
    out.append(f'  (State {" ".join(str(v) for v in vals)}) ; {nuc(n)}')
out[-1] = out[-1].replace(') ;', '))) ;', 1)
out.append('')

fields = ['doomednum', 'spawn-state', 'spawn-health', 'see-state', 'see-sound',
          'reaction-time', 'attack-sound', 'pain-state', 'pain-chance', 'pain-sound',
          'melee-state', 'missile-state', 'death-state', 'xdeath-state', 'death-sound',
          'speed', 'radius', 'height', 'mass', 'damage', 'active-sound', 'flags',
          'raise-state']
out.append('(defstruct MobjInfo')
for i in range(0, len(fields), 5):
    out.append('  ' + ' '.join(f + ':i32' for f in fields[i:i + 5]))
out[-1] += ')'
out.append('')
out.append('(defconst MOBJINFO (array MobjInfo')
for r, n in zip(mobj_rows, mobjtypes):
    out.append(f'  (MobjInfo {" ".join(str(value(v)) for v in r)}) ; {nuc(n)}')
out[-1] = out[-1].replace(') ;', '))) ;', 1)
out.append('''
(defn state-at (s:i32):State (return (aref STATES (as i64 s))))
(defn mobj-info (t:i32):MobjInfo (return (aref MOBJINFO (as i64 t))))''')

open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
