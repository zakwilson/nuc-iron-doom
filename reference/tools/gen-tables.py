#!/usr/bin/env python3
"""gen-tables.py TABLES_C OUT_NUC: Chocolate Doom's trig tables as Nucleus.

The tables can't be recomputed: no rounding of sin, tan or atan reproduces
them (33, 204 and about 1,880 entries differ), so they're embedded, and
src/tests/tables.nuc checks them against tables.c when it's present.
"""
import re, sys

src = open(sys.argv[1]).read()

def table(name):
    m = re.search(r'\b' + name + r'\[[^\]]*\]\s*=\s*\{(.*?)\};', src, re.S)
    body = re.sub(r'//.*', '', m.group(1))
    return [int(x, 0) for x in re.findall(r'-?(?:0x[0-9a-fA-F]+|\d+)', body)]

def emit(out, name, ty, values, comment):
    out.append(f'; {comment}')
    out.append(f'(defconst {name} (array {ty}')
    for i in range(0, len(values), 8):
        out.append('   ' + ' '.join(str(v) for v in values[i:i + 8]))
    out[-1] += '))'
    out.append('')

out = ['''; Copyright (C) 1993-1996 Id Software, Inc.
; Copyright (C) 2005-2014 Simon Howard
; GPLv2 or later (Chocolate Doom src/tables.c); this port is GPLv3, see COPYING.
;
; Generated by reference/tools/gen-tables.py from tables.c. Don't edit.
; Embedded, not computed: no rounding of sin, tan or atan reproduces them.

(ns doom.tables)
''']
emit(out, 'FINETANGENT', 'i32', table('finetangent'),
     'tan of each fine angle from -90 to +90 degrees, in fixed point.')
emit(out, 'FINESINE', 'i32', table('finesine'),
     'sin over 5/4 of a turn, so cosine is the same table from FINEANGLES/4.')
emit(out, 'TANTOANGLE', 'ui32', [v & 0xffffffff for v in table('tantoangle')],
     'atan of slope/2048 for slope 0..2048, as a binary angle.')
open(sys.argv[2], 'w').write('\n'.join(out))
